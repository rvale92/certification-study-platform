import type { Question } from './examQuestions';

type FourOptions = [string, string, string, string];
type ThreeReasons = [string, string, string];

const makeQuestion = (
  id: string,
  domain: string,
  question: string,
  options: FourOptions,
  correctIndex: number,
  explanation: string,
  distractorReasons: ThreeReasons,
): Question => {
  if (correctIndex < 0 || correctIndex >= options.length) {
    throw new Error(`Invalid correct-answer index for ${id}.`);
  }

  const correctAnswer = options[correctIndex];
  const distractorExplanations: Record<string, string> = {};
  let reasonIndex = 0;
  options.forEach((option, index) => {
    if (index !== correctIndex) {
      distractorExplanations[option] = distractorReasons[reasonIndex];
      reasonIndex += 1;
    }
  });

  return { id, domain, question, options, correctAnswer, explanation, distractorExplanations };
};

